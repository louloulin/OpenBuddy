#!/usr/bin/env node
/**
 * generate-notices.mjs — 生成 THIRD-PARTY-NOTICES.md(P0.9,2026-10-19)。
 *
 * 扫描 node_modules/.pnpm 下每个包的 package.json(name/version/license/
 * homepage/repository),排除本仓 workspace 包(@openbuddy/*、@earendil-works
 * 的自研包除外——earendil 是真实第三方依赖),按字母序输出许可清单。
 *
 * 口径:全量扫描(含 devDependencies)—— 故意从宽;发布的 app 实际打包面是
 * root dependencies 的子集,许可清单覆盖超集在法律上只有更安全。
 *
 * Usage: node scripts/generate-notices.mjs   (输出 THIRD-PARTY-NOTICES.md)
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const pnpmDir = join(root, "node_modules", ".pnpm");
if (!existsSync(pnpmDir)) {
  console.error("[notices] node_modules/.pnpm not found — run pnpm install first");
  process.exit(1);
}

const WORKSPACE_SCOPES = ["@openbuddy"];

/** 从包目录读许可元数据;缺 package.json 时跳过。 */
function collectPackage(pkgDir) {
  const manifestPath = join(pkgDir, "package.json");
  if (!existsSync(manifestPath)) return null;
  try {
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    const name = manifest.name;
    if (!name) return null;
    if (WORKSPACE_SCOPES.some((scope) => name.startsWith(`${scope}/`))) return null;
    let license = manifest.license;
    if (Array.isArray(license)) license = license.join(" OR ");
    if (typeof license !== "string" || license.trim().length === 0) license = "UNKNOWN";
    // 常见简写归一("MIT License" → "MIT")。
    license = license.replace(/\s+license/i, "").trim();
    const repository =
      typeof manifest.repository === "string"
        ? manifest.repository
        : typeof manifest.repository?.url === "string"
          ? manifest.repository.url
          : manifest.homepage ?? "";
    const licenseFile = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "README"]
      .map((base) => [base, `${base}.md`, `${base}.txt`])
      .flat()
      .map((file) => join(pkgDir, file))
      .find((file) => existsSync(file));
    return { name, version: manifest.version ?? "?", license, repository, licenseFile };
  } catch {
    return null;
  }
}

// pnpm 11 的布局是**平铺 node_modules**(包实体直接在 node_modules/<name>,
// 元数据在 .package-map.json),不再有 .pnpm 虚拟商店。直接扫两层。
const packages = new Map();
const modulesDir = join(root, "node_modules");
for (const entry of readdirSync(modulesDir)) {
  if (entry.startsWith(".")) continue;
  const entryPath = join(modulesDir, entry);
  if (entry.startsWith("@")) {
    for (const pkgName of readdirSync(entryPath)) {
      const info = collectPackage(join(entryPath, pkgName));
      if (info) packages.set(`${info.name}@${info.version}`, info);
    }
  } else {
    const info = collectPackage(entryPath);
    if (info) packages.set(`${info.name}@${info.version}`, info);
  }
}

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
const licenseCounts = {};
for (const info of sorted) {
  licenseCounts[info.license] = (licenseCounts[info.license] ?? 0) + 1;
}

const lines = [
  "# Third-Party Notices",
  "",
  `Generated by \`scripts/generate-notices.mjs\` on ${new Date().toISOString()}.`,
  `${sorted.length} third-party packages (superset of the packaged dependency tree;`,
  "do not edit by hand).",
  "",
  "## License summary",
  "",
  ...Object.entries(licenseCounts)
    .sort((a, b) => b[1] - a[1])
    .map(([license, count]) => `- ${license}: ${count}`),
  "",
  "## Packages",
  "",
  "| Package | Version | License | Repository |",
  "|---|---|---|---|",
  ...sorted.map(
    (info) =>
      `| ${info.name} | ${info.version} | ${info.license} | ${info.repository.replace(/\|/g, "%7C")} |`,
  ),
  "",
];

// 附上各包的 LICENSE 原文(有文件才附;UNKNOWN 且无文件的保持仅表格行)。
const withFile = sorted.filter((info) => info.licenseFile);
lines.push("## Full license texts", "");
for (const info of withFile) {
  lines.push(`### ${info.name}@${info.version} — ${info.license}`, "");
  try {
    const text = readFileSync(info.licenseFile, "utf8");
    lines.push("```", text.trimEnd(), "```", "");
  } catch { /* 读取失败保持空节 */ }
}

const outPath = join(root, "THIRD-PARTY-NOTICES.md");
writeFileSync(outPath, lines.join("\n"));
console.log(`[notices] wrote ${outPath} (${sorted.length} packages, ${withFile.length} license texts)`);
