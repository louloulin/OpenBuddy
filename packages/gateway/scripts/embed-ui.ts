/**
 * Embeds the built console into the gateway as generated TypeScript.
 *
 * The gateway normally serves `gateway-ui/dist` from disk. A packaged binary has
 * no such directory next to it, so this script turns every built file into a
 * base64 literal and emits an entry point that installs the map before the
 * gateway starts. `bun build --compile` then produces one executable that serves
 * `/ui` with no side files.
 *
 * Usage:
 *   bun run scripts/embed-ui.ts                 # ../gateway-ui/dist
 *   GATEWAY_UI_DIR=/path/to/dist bun run scripts/embed-ui.ts
 *   bun run scripts/embed-ui.ts --dir=/path/to/dist
 *   bun run scripts/embed-ui.ts --check         # fail if generated output is stale
 */

import { mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises'
import { join, relative, resolve, sep } from 'node:path'

const gatewayRoot = resolve(import.meta.dir, '..')
const generatedDir = join(gatewayRoot, 'src', 'generated')
const assetsFile = join(generatedDir, 'uiAssets.ts')
const entryFile = join(generatedDir, 'index.embedded.ts')

function argumentValue(prefix: string): string | null {
  const match = process.argv.find(value => value.startsWith(`${prefix}=`))
  return match ? match.slice(prefix.length + 1) : null
}

const checkOnly = process.argv.includes('--check')
const uiDir = resolve(
  argumentValue('--dir')
    ?? process.env.GATEWAY_UI_DIR
    ?? join(gatewayRoot, '..', 'gateway-ui', 'dist'),
)

type Collected = { key: string; bytes: Uint8Array }

async function collect(directory: string, prefix = ''): Promise<Collected[]> {
  const entries = await readdir(directory, { withFileTypes: true })
  entries.sort((left, right) => left.name.localeCompare(right.name))
  const files: Collected[] = []
  for (const entry of entries) {
    // A packaged build should contain only output; dotfiles are editor or OS
    // junk that would otherwise ride along invisibly.
    if (entry.name.startsWith('.')) continue
    const absolute = join(directory, entry.name)
    const key = prefix ? `${prefix}/${entry.name}` : entry.name
    if (entry.isDirectory()) {
      files.push(...await collect(absolute, key))
    } else if (entry.isFile()) {
      files.push({ key, bytes: new Uint8Array(await readFile(absolute)) })
    }
  }
  return files
}

function generatedAssets(files: Collected[], source: string): string {
  const lines = files.map(
    file => `  ${JSON.stringify(file.key)}: ${JSON.stringify(Buffer.from(file.bytes).toString('base64'))},`,
  )
  return `// Generated by scripts/embed-ui.ts from ${source} — do not edit.
// Regenerate with: bun run ui:embed

import type { UiAssetMap } from '../ui.js'

/** Path inside the console build → base64 bytes. */
const ASSETS: Record<string, string> = {
${lines.join('\n')}
}

/** The build, decoded once at process start. */
export function embeddedUiAssets(): UiAssetMap {
  const assets = new Map<string, Uint8Array>()
  for (const [path, encoded] of Object.entries(ASSETS)) {
    assets.set(path, Uint8Array.from(Buffer.from(encoded, 'base64')))
  }
  return assets
}
`
}

function generatedEntry(): string {
  return `// Generated by scripts/embed-ui.ts — do not edit.
// Regenerate with: bun run ui:embed

import { setEmbeddedUi } from '../ui.js'
import { embeddedUiAssets } from './uiAssets.js'

setEmbeddedUi(embeddedUiAssets())

// The gateway entry starts Bun.serve on import. Load it only after the assets
// are installed, or the first request can race an empty embedded map.
await import('../index.js')
`
}

const index = join(uiDir, 'index.html')
try {
  if (!(await stat(index)).isFile()) throw new Error('not a file')
} catch {
  console.error(
    `[embed-ui] no console build at ${uiDir}\n`
      + '  Build it first: cd gateway-ui && bun install && bun run build',
  )
  process.exit(1)
}

const files = await collect(uiDir)
if (!files.some(file => file.key === 'index.html')) {
  console.error('[embed-ui] the build has no index.html')
  process.exit(1)
}

const source = relative(gatewayRoot, uiDir).split(sep).join('/') || '.'
const assetsText = generatedAssets(files, source)
const entryText = generatedEntry()
const totalBytes = files.reduce((sum, file) => sum + file.bytes.byteLength, 0)

if (checkOnly) {
  const currentAssets = await readFile(assetsFile, 'utf8').catch(() => null)
  const currentEntry = await readFile(entryFile, 'utf8').catch(() => null)
  if (currentAssets !== assetsText || currentEntry !== entryText) {
    console.error('[embed-ui] generated files are stale; run: bun run ui:embed')
    process.exit(1)
  }
  console.log(`[embed-ui] up to date (${files.length} files, ${totalBytes} bytes)`)
  process.exit(0)
}

await rm(generatedDir, { recursive: true, force: true })
await mkdir(generatedDir, { recursive: true })
await writeFile(assetsFile, assetsText)
await writeFile(entryFile, entryText)

console.log(
  `[embed-ui] embedded ${files.length} files (${(totalBytes / 1024).toFixed(1)} KiB) from ${source}`,
)
console.log(`[embed-ui] wrote ${relative(gatewayRoot, entryFile).split(sep).join('/')}`)
